package fr.neamar.kiss.utils;

import android.content.ComponentName;
import android.content.Context;
import android.content.Intent;
import android.content.pm.ActivityInfo;
import android.content.pm.PackageManager;
import android.graphics.Rect;
import android.net.Uri;

/** User-tap-only handoff to Ice Box's own unfreeze-and-launch engine. No service or polling. */
public final class IceBoxLaunchBridge {
    public static final String PACKAGE = "com.catchingnow.icebox";
    private static final ComponentName ACTION = new ComponentName(PACKAGE,
            PACKAGE + ".activity.ShortcutActionActivity");

    private IceBoxLaunchBridge() { }

    public static boolean open(Context context, String target, int userId, Rect sourceBounds) {
        if (!IceBoxShortcutIdentity.isPackageName(target) || PACKAGE.equals(target) || userId < 0) {
            return false;
        }
        try {
            ActivityInfo info = context.getPackageManager().getActivityInfo(ACTION, 0);
            if (!info.exported || !info.enabled || !info.applicationInfo.enabled) return false;
            // This is the URI generated by Ice Box itself for app shortcuts. Let its own
            // Device Owner / Shizuku / root engine finish enabling before opening the app.
            Intent intent = new Intent(Intent.ACTION_VIEW, new Uri.Builder().scheme("icebox")
                    .authority("action").appendPath("run_app").appendPath(target)
                    .appendQueryParameter("user", Integer.toString(userId)).build())
                    .setComponent(ACTION).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            intent.setSourceBounds(sourceBounds);
            context.startActivity(intent);
            AppLaunchUtils.invalidatePackageState(target);
            return true;
        } catch (PackageManager.NameNotFoundException | RuntimeException e) {
            Log.w("IceBoxLaunchBridge", "Ice Box app-opening route unavailable", e);
            return false;
        }
    }
}
